FORMAT_RETRY_REASONS = frozenset({
    'invalid_json', 'duplicate_fields', 'invalid_fields', 'invalid_field_type',
    'invalid_manager_type', 'context_too_long', 'empty_context', 'empty_reply',
    'name_too_long', 'service_marker', 'invalid_type', 'response_too_long', 'response_truncated',
}) | TOOL_RESPONSE_ERRORS


def format_retry_messages(messages: list, reason: str, *, use_tools: bool = True) -> list:
    """Regenerate from original input with a trusted format-only reminder."""
    from langchain_core.messages import SystemMessage

    if (reason not in FORMAT_RETRY_REASONS or not messages
            or not isinstance(messages[0], SystemMessage) or not isinstance(messages[0].content, str)):
        raise ValueError('invalid_format_retry_input')
    reminder = '\n\n[ПОВТОР ПОСЛЕ ОШИБКИ ФОРМАТА: ' + reason + ']\nОтветь заново на исходный запрос, соблюдая все правила выше.' + (_RESPONSE_RULES if use_tools else _JSON_RESPONSE_RULES)
    if reason == 'incomplete_tool_arguments':
        reminder += ('\nПредыдущие аргументы функции оборвались до завершения JSON. '
                     'Не продолжай частичный ответ: заново верни один полный вызов prepare_response. '
                     'Укажи оба значения reply и manager; manager должен быть null либо полным объектом '
                     'context/type/name. Обязательно закрой все строки и скобки JSON.')
    if reason in {'response_truncated', 'response_too_long'}:
        reminder += '\nСократи формулировки, сохрани нужные факты и ссылки; верни полностью завершённый ответ.'
    return [messages[0].model_copy(update={'content': messages[0].content + reminder}), *messages[1:]]


